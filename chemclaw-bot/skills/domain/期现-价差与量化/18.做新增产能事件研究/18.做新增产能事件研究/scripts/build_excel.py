def main():
    a = json.load(open(os.path.join(OUT, "analysis.json"), encoding="utf-8"))
    ev = json.load(open(os.path.join(DATA, "events_pp.json"), encoding="utf-8"))
    wb = Workbook()
    wb.remove(wb.active)

