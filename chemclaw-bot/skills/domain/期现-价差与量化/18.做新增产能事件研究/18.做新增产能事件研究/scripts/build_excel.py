def _csv_sheet(wb, name, path, spec_map=None, note=None):
    ws = wb.create_sheet(name)
    if not os.path.exists(path):
        ws.append(["数据缺失", path])
        return ws
    with open(path, "r", encoding="utf-8-sig", newline="") as f:
        rd = csv.reader(f)
        for i, row in enumerate(rd):
            ws.append(row)
            if i > 4000:
                break
    style_header(ws)
    autosize(ws, maxw=30)
    ws.freeze_panes = "A2"
    return ws


def sheet_event_windows(wb, a):
    ws = wb.create_sheet("06_事件窗口_逐事件")
    ws.append(["事件ID", "项目名称", "区域", "设计产能(万吨/年)", "阶段", "事件日期",
               "序列", "跨度(交易日)", "基准值", "后段值", "后段日期",
               "累计变化", "相对日历超额", "突变(二阶差分)", "占现有产能(%)", "±120日内其他项目数"])
    for r in a["per_event"]:
        for vk, paths in r["vars"].items():
            if "_status" in paths:
                continue
            for h in a["horizons"]:
                p = paths.get(str(h)) or paths.get(h)
                if not isinstance(p, dict):
                    continue
                ws.append([r["event_id"], r["project_name"], r.get("region"),
                           r.get("design_capacity"), STAGE_CN.get(r["stage"], r["stage"]), r["date"],
                           vk, h, p.get("base_value"), p.get("post_value"), p.get("post_date"),
                           p.get("pct"), p.get("abnormal_pct"), p.get("surprise_pct"),
                           r.get("share_pct"), r.get("concurrent_projects_within_120d")])
    style_header(ws)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.border = BORDER
            if c.column in (12, 13, 14) and isinstance(c.value, (int, float)):
                c.number_format = "0.00%"
            if c.column == 15 and isinstance(c.value, (int, float)):
                c.number_format = "0.000"
    autosize(ws)
    ws.freeze_panes = "C2"
    ws.auto_filter.ref = ws.dimensions
    return ws


def sheet_aggregate(wb, a):
    ws = wb.create_sheet("07_汇总统计")
    ws.append(["序列", "阶段", "阶段名称", "跨度(交易日)", "样本数 n",
               "累计变化均值", "累计变化中位", "标准差", "t(累计)",
               "超额变化均值", "t(超额)", "突变均值", "t(突变)",
               "上涨比例", "符号检验 p", "bootstrap 90%下限", "bootstrap 90%上限", "样本不足"])
    for r in a["aggregate"]:
        ws.append([r["var"], r["stage"], r["stage_label"], r["horizon"], r["n"],
                   r["mean_pct"], r["median_pct"], r["sd_pct"], r["t_cum"],
                   r["mean_abnormal"], r["t_abnormal"], r["mean_surprise"], r["t_surprise"],
                   r["pos_share"], r["sign_p"], r["ci90_lo"], r["ci90_hi"],
                   "是" if r["insufficient"] else "否"])
    style_header(ws)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.border = BORDER
            if c.column in (6, 7, 8, 10, 12, 14, 16, 17) and isinstance(c.value, (int, float)):
                c.number_format = "0.0000"
        if row[17].value == "是":
            row[17].fill = WARN_FILL
    autosize(ws)
    ws.freeze_panes = "B2"
    ws.auto_filter.ref = ws.dimensions
    return ws


def sheet_placebo(wb, a):
    ws = wb.create_sheet("08_安慰剂检验")
    ws.append(["序列", "跨度(交易日)", "事件数", "真实均值", "随机均值", "随机标准差",
               "真实值分位", "双尾 p 值", "抽签次数", "判读"])
    for k, v in a["placebo"].items():
        vk, h = k.split("@")
        if v.get("_status"):
            ws.append([vk, int(h), None, None, None, None, None, None, None, "数据不足"])
            continue
        sig = v["p_value_two_sided"] < 0.10
        ws.append([vk, int(h), v["n_events"], v["real_mean_pct"], v["placebo_mean"],
                   v["placebo_sd"], v["real_percentile"], v["p_value_two_sided"], v["n_draws"],
                   "与随机噪声有差异" if sig else "与随机噪声无法区分"])
    style_header(ws)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.border = BORDER
            if c.column in (4, 5, 6) and isinstance(c.value, (int, float)):
                c.number_format = "0.00%"
    autosize(ws)
    return ws


def sheet_capacity(wb, a, ev):
    ws = wb.create_sheet("09_产能占比与爬坡")
    ws["A1"] = "设计产能 ≠ 投产当天实际产量：按爬坡曲线换算"
    ws["A1"].font = TITLE_FONT
    ws["A2"] = a["ramp_assumption"]
    ws["A2"].font = SUB_FONT
    ws["A2"].alignment = Alignment(wrap_text=True)
    r0 = 4
    ws.cell(row=r0, column=1, value="爬坡曲线（投产第 N 个月的设计负荷比例，工程假设）").font = Font(bold=True)
    ws.append([])
    hdr_row = 5
    for i, v in enumerate(a["default_ramp"]):
        c = ws.cell(row=hdr_row, column=1 + i, value="M%d" % (i + 1))
        c.fill = HDR_FILL
        c.font = HDR_FONT
        c.alignment = Alignment(horizontal="center")
        ws.cell(row=hdr_row + 1, column=1 + i, value=v).number_format = "0%"
    r0 = hdr_row + 3
    cols = ["项目", "设计产能(万吨/年)", "投产日期", "投产年行业产能(万吨/年)", "占现有产能(%)",
            "投产首月实际增量(万吨)", "第3月(万吨)", "第6月(万吨)", "首12个月累计产量(万吨)"]
    for i, cname in enumerate(cols):
        c = ws.cell(row=r0, column=1 + i, value=cname)
        c.fill = HDR_FILL
        c.font = HDR_FONT
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BORDER
    ws.row_dimensions[r0].height = 34
    seen = []
    for e in ev["events"]:
        if e["project_id"] in seen:
            continue
        if e["stage"] not in ("startup", "commissioning"):
            continue
        seen.append(e["project_id"])
        dv = e["design_capacity"]
        ramp = a["default_ramp"]
        m0 = dv * ramp[0] * 30 / 365
        m3 = dv * ramp[3] * 30 / 365
        m6 = dv * ramp[6] * 30 / 365
        c12 = sum(ramp) * dv * 30 / 365
        r = ws.max_row + 1
        vals = [e["project_name"], dv, e["date"],
                ev["meta"]["capacity_base_wt"].get(e["date"][:4]),
                round(100.0 * dv / ev["meta"]["capacity_base_wt"][e["date"][:4]], 3)
                if ev["meta"]["capacity_base_wt"].get(e["date"][:4]) else None,
                round(m0, 2), round(m3, 2), round(m6, 2), round(c12, 1)]
        for i, v in enumerate(vals):
            c = ws.cell(row=r, column=1 + i, value=v)
            c.border = BORDER
    autosize(ws)
    return ws


