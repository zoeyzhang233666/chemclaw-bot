def sheet_projects(wb, a, ev):
    ws = wb.create_sheet("01_候选项目表")
    cols = ["项目ID", "项目名称", "业主", "地点", "区域", "工艺路线", "上游配套",
            "设计产能(万吨/年)", "投产年", "当年行业产能(万吨/年)", "占现有产能(%)",
            "首次预计投产", "实际投产", "延期(月)", "证据等级", "单一来源", "备注"]
    ws.append(cols)
    cap = ev["meta"]["capacity_base_wt"]
    for p in ev["projects"]:
        st = p["stages"].get("startup") or p["stages"].get("commissioning") or {}
        yr = (st.get("date") or "")[:4]
        base = cap.get(yr)
        dv = p.get("design_capacity")
        share = round(100.0 * dv / base, 3) if (base and dv) else None
        single = "是" if st.get("single_source") else "否"
        ws.append([p["project_id"], p["name"], p.get("owner"), p.get("location"), p.get("region"),
                   p.get("process"), p.get("upstream"), dv, yr, base, share,
                   p.get("first_estimate"), p.get("actual"), p.get("delay_months"),
                   st.get("grade"), single, p.get("note", "")])
    style_header(ws)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.border = BORDER
            c.alignment = Alignment(vertical="top", wrap_text=(c.column in (3, 4, 7, 17)))
    autosize(ws)
    ws.freeze_panes = "C2"
    ws.auto_filter.ref = ws.dimensions
    return ws


