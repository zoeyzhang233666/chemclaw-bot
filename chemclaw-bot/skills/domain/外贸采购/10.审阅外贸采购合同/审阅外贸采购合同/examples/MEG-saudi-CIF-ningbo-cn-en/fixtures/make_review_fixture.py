def _recount(findings):
    kind = Counter(f["kind"] for f in findings)
    sev = Counter(f["severity"] for f in findings)
    topic = Counter(f["topic"] for f in findings)
    return {
        "total": len(findings),
        "by_kind": dict(kind),
        "by_severity": {str(k): sev[k] for k in sorted(sev)},
        "by_topic": dict(topic),
    }


