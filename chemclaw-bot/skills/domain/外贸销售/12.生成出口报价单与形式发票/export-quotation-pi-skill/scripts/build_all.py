#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""End-to-end build of the export-quotation / proforma-invoice skill.

Produces, under OUTPUT/:
  deliverables/   interactive HTML editor + Quotation & PI in DOCX/PDF + data workbook
  examples/       one folder per trade-condition example (DOCX + PDF + workbook + HTML)
  QA_report.md    engine state, totals, computed vs. independent check
"""
import argparse, io, json, os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PY = sys.executable
NODE = os.environ.get("QUOTE_NODE") or "node"


def run(mod, *args):
    cmd = [PY, os.path.join(HERE, mod)] + list(args)
    r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        raise SystemExit("FAILED %s\n%s\n%s" % (mod, r.stdout[-2000:], r.stderr[-3000:]))
    return r.stdout


def jrun(mod, *args):
    out = run(mod, *args)
    line = [l for l in out.splitlines() if l.strip().startswith("{")]
    return json.loads(line[-1]) if line else {}


def engine(case_path):
    return jrun("engine_check.py", case_path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "dist"))
    ap.add_argument("--skip-pdf", action="store_true")
    a = ap.parse_args()
    out = a.out
    deliv = os.path.join(out, "deliverables")
    exout = os.path.join(out, "examples")
    for d in (out, deliv, exout):
        os.makedirs(d, exist_ok=True)

    cases = {}
    for f in sorted(os.listdir(os.path.join(ROOT, "examples"))):
        if f.startswith("case-ex0") and f.endswith(".json"):
            cases[f.split("-")[1].upper()] = os.path.join(ROOT, "examples", f)

    lines = ["# Build & QA report", "",
             "Generated by `scripts/build_all.py`. Every case below is **SIMULATED demo data**.", "",
             "| Case | Type | Rule | State | Errors | Warnings | Total | Independent check |",
             "|---|---|---|---|---|---|---|---|"]
    for cid, path in cases.items():
        base = json.loads(io.open(path, encoding="utf-8").read())
        cid = folder = cid.replace("-", "")
        target = deliv if folder == "EX001" else os.path.join(exout, folder)
        os.makedirs(target, exist_ok=True)
        stem = "%s_" % base.get("docType", "QUOTATION").replace("PROFORMA_INVOICE", "Proforma_Invoice").upper()[:16]
        pdf_flag = [] if a.skip_pdf else ["--pdf"]
        for dtype in ("QUOTATION", "PROFORMA_INVOICE"):
            name = os.path.join(target, "%s_%s_%s" % (cid, base["reference"]["quoteNo"], "Proforma_Invoice" if dtype == "PROFORMA_INVOICE" else "Quotation"))
            res = jrun("build_docx.py", "--case", path, "--out", name + ".docx", "--doc-type", dtype, *pdf_flag)
            print("docx", res.get("docx"))
        wb = os.path.join(target, "%s_%s_Data_Workbook.xlsx" % (cid, base["reference"]["quoteNo"]))
        jrun("build_xlsx.py", "--case", path, "--out", wb)
        html = os.path.join(target, "%s_%s_Studio.html" % (cid, base["reference"]["quoteNo"]))
        run("build_studio_html.py", "--data", path, "--out", html)
        ev = engine(path)
        chk = "OK (%s)" % ev.get("independent_total") if ev.get("independent_match") else "MISMATCH (%s)" % ev.get("independent_total")
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            cid, base.get("docType"), (base.get("tradeTerm") or {}).get("code"),
            ev.get("state"), ev.get("errors"), ev.get("warnings"),
            ev.get("total"), chk))
    io.open(os.path.join(out, "QA_report.md"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
